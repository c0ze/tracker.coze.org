#!/usr/bin/env node
/**
 * sound-library — browse and audition the synth presets (tools/synth-presets.js).
 *
 *   node tools/sound-library.js                      print the catalog (Markdown)
 *   node tools/sound-library.js --write              regenerate docs/sound-library.md
 *   node tools/sound-library.js --audition bass.pluck [out.it]
 *                                                    build a short audition module
 *                                                    (default build/audition/<preset>.it);
 *                                                    then: node tools/render.js <out.it>
 *
 * songs/sound_library.gen.js strings every audition pattern into one module.
 * auditionPattern() is plain data so that generator needs only this file and the presets.
 */
import { PRESETS } from './synth-presets.js';

const NAMES = ['C-', 'C#', 'D-', 'D#', 'E-', 'F-', 'F#', 'G-', 'G#', 'A-', 'A#', 'B-'];
const nn = (s) => NAMES.indexOf(s.slice(0, 2)) + 12 * Number(s[2]);
const ns = (n) => NAMES[n % 12] + Math.floor(n / 12);
const clampNote = (n, [lo, hi]) => ns(Math.max(nn(lo), Math.min(nn(hi), n)));

export const AUDITION = { bpm: 120, ticks: 6, rows: 64 };

/**
 * One 64-row, 3-channel pattern that demonstrates `preset` played on sample `inst`:
 * drums get isolated hits, an accent figure and their pitch range; pitched sounds
 * get a note at C-5 (or their range), both ends of the range and a held triad, each
 * with the articulation the preset needs (loops get written envelopes and cuts).
 */
export function auditionPattern(preset, inst) {
  const p = PRESETS[preset];
  if (!p) throw new Error(`Unknown preset: ${preset}`);
  const ch = [{}, {}, {}], hit = (c, row, note, vol) => { ch[c][row] = { note, instrument: inst, vol: `v${vol}` }; };
  const cut = (c, row) => { ch[c][row] = { note: '^^' }; };
  const looped = p.synth.wave === 'additive' || p.synth.wave === 'ensemble' || p.synth.wave === 'pwm';
  if (p.role === 'percussion' || p.role === 'fx') {
    if (p.role === 'fx') {
      hit(0, 0, 'C-5', 56);
      hit(0, 32, clampNote(nn('C-5') - 5, ['G-4', 'C-5']), 56);
      cut(0, 63);
    } else {
      [0, 8, 16, 24].forEach((row) => hit(0, row, 'C-5', 56));
      for (let row = 32; row < 48; row += 2) hit(0, row, 'C-5', row % 8 === 0 ? 56 : row % 4 === 0 ? 34 : 20);
      hit(0, 48, p.range[0], 52); hit(0, 52, 'C-5', 52); hit(0, 56, p.range[1], 52);
      cut(0, 62);
    }
    return { name: preset, rows: AUDITION.rows, channels: ch };
  }
  // A held note: loops get attack, held level, fade and cut; shots ring until their cut.
  const note = (c, row, n, len, vol = 44) => {
    if (p.role === 'pad') { // pads swell in and fade to silence before the cut, as the catalog says to play them
      hit(c, row, n, Math.round(vol * 0.2));
      ch[c][row + 2] = { vol: `v${Math.round(vol * 0.55)}` };
      ch[c][row + 4] = { vol: `v${vol}` };
      if (len > 12) ch[c][row + (len >> 1)] = { vol: `v${Math.round(vol * 0.85)}` };
      ch[c][row + len - 3] = { vol: `v${Math.round(vol * 0.45)}` };
      ch[c][row + len - 2] = { vol: `v${Math.round(vol * 0.15)}` };
      ch[c][row + len - 1] = { vol: 'v00' };
      cut(c, row + len);
      return;
    }
    hit(c, row, n, vol);
    if (looped) {
      ch[c][row + 1] = { vol: `v${Math.round(vol * 0.8)}` };
      if (len > 12) ch[c][row + (len >> 1)] = { vol: `v${Math.round(vol * 0.7)}` };
      ch[c][row + len - 2] = { vol: `v${Math.round(vol * 0.45)}` };
      ch[c][row + len - 1] = { vol: `v${Math.round(vol * 0.2)}` };
    }
    cut(c, row + len);
  };
  const home = nn(clampNote(nn(p.role === 'bass' ? 'C-4' : 'C-5'), p.range));
  note(0, 0, ns(home), 10);
  note(0, 12, p.range[0], 10);
  note(0, 24, p.range[1], 10);
  const root = Math.min(home, nn(p.range[1]) - 7);
  [0, 4, 7].forEach((semi, c) => note(c, 36, ns(root + semi), 24, 34));
  return { name: preset, rows: AUDITION.rows, channels: ch };
}

/** A sample definition that uses the preset by name. */
export const presetSample = (preset) => ({ name: preset, ...(PRESETS[preset].role === 'percussion' ? { role: 'percussion' } : {}), synth: { preset } });

export function auditionSong(preset) {
  return {
    title: `Audition: ${preset}`, bpm: AUDITION.bpm, ticks: AUDITION.ticks, mixvol: 64,
    samples: [presetSample(preset)], patterns: [auditionPattern(preset, 0)], order: [0],
  };
}

export function catalog() {
  const groups = [['percussion', 'Drums and percussion'], ['bass', 'Basses'], ['keys', 'Keys and mallets'], ['lead', 'Leads'], ['pad', 'Pads'], ['fx', 'Effects']];
  const mode = (p) => (['additive'].includes(p.synth.wave) ? 'cycle' : ['ensemble', 'pwm'].includes(p.synth.wave) ? 'loop' : 'shot');
  const lines = [
    '# Sound library',
    '',
    'Generated by `node tools/sound-library.js --write` from [tools/synth-presets.js](../tools/synth-presets.js); edit the presets, not this file.',
    '',
    'Every sound is synthesized and deterministic, so songs that use it build on a fresh clone and in the browser player.',
    'Use a preset by name, optionally overriding its own parameters:',
    '',
    '```json',
    '{ "name": "snare", "synth": { "preset": "snare.tight" } }',
    '{ "name": "snare 2", "synth": { "preset": "snare.tight", "seed": 9, "tone": 210 } }',
    '```',
    '',
    '**Modes.** A *shot* bakes its own decay and ends by itself (its length changes with pitch: an octave down lasts twice as long).',
    'A *cycle* is one static period and a *loop* a longer moving one; both hold at full level until you write a volume',
    'shape and a `^^` cut, because sample mode has no envelopes. Ranges are where a sound reads well, not hard limits.',
    '',
    'Audition one sound: `node tools/sound-library.js --audition <preset>`, then `node tools/render.js build/audition/<preset>.it`.',
    'All of them in one module: `songs/sound_library.gen.js` (one 8-second pattern per preset, in this order).',
    '',
  ];
  for (const [role, title] of groups) {
    lines.push(`## ${title}`, '', '| Preset | Mode | Range | Sound | How to play it |', '|---|---|---|---|---|');
    for (const [name, p] of Object.entries(PRESETS)) if (p.role === role) {
      const range = p.range[0] === p.range[1] ? p.range[0] : `${p.range[0]}–${p.range[1]}`;
      lines.push(`| \`${name}\` | ${mode(p)} | ${range} | ${p.about} | ${p.play} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const fs = await import('node:fs');
  const path = await import('node:path');
  const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
  const args = process.argv.slice(2);
  if (args[0] === '--write') {
    fs.writeFileSync(path.join(root, 'docs/sound-library.md'), catalog());
    console.log('wrote docs/sound-library.md');
  } else if (args[0] === '--audition') {
    const preset = args[1];
    if (!PRESETS[preset]) { console.error(`Unknown preset: ${preset}\nKnown: ${Object.keys(PRESETS).join(', ')}`); process.exit(1); }
    const { default: itwriter } = await import('../vendor/itwriter/index.js');
    const { resolveSample } = await import('./resolve-sample.js');
    const { assertSong } = await import('./validate-song.js');
    const song = auditionSong(preset);
    assertSong(song);
    song.samples = song.samples.map(resolveSample);
    const out = args[2] ?? path.join(root, 'build/audition', `${preset}.it`);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, Buffer.from(itwriter(song)));
    console.log(`wrote ${path.relative(process.cwd(), out)}`);
  } else if (args.length === 0) {
    console.log(catalog());
  } else {
    console.error('Usage: node tools/sound-library.js [--write | --audition <preset> [out.it]]');
    process.exit(1);
  }
}
